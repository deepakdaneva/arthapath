// Writes src/environments/firebase-config.ts from environment variables.
//
// Firebase web config values are public identifiers (they ship in the built
// JavaScript), but they are kept out of git so every deployer uses their own
// projects. With no variables set, the app targets the local emulators with
// the demo-arthapath project, which cannot reach any real Firebase project.
import { mkdirSync, writeFileSync } from 'node:fs';

const env = process.env;
const real = Boolean(env.FIREBASE_PROJECT_ID && env.FIREBASE_API_KEY && env.FIREBASE_APP_ID);

const config = real
  ? {
      apiKey: env.FIREBASE_API_KEY,
      authDomain: env.FIREBASE_AUTH_DOMAIN || `${env.FIREBASE_PROJECT_ID}.firebaseapp.com`,
      projectId: env.FIREBASE_PROJECT_ID,
      appId: env.FIREBASE_APP_ID,
      messagingSenderId: env.FIREBASE_MESSAGING_SENDER_ID || '',
    }
  : {
      apiKey: 'demo-api-key',
      authDomain: 'demo-arthapath.firebaseapp.com',
      projectId: 'demo-arthapath',
      appId: 'demo-app-id',
      messagingSenderId: '',
    };

const out = `// Generated by scripts/write-firebase-config.mjs. Do not edit or commit.
export const firebaseConfig = ${JSON.stringify(config, null, 2)} as const;
export const useEmulators = ${!real};
`;

mkdirSync('src/environments', { recursive: true });
writeFileSync('src/environments/firebase-config.ts', out);
console.log(`Firebase config: ${real ? config.projectId : 'local emulators (demo-arthapath)'}`);
