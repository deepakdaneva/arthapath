// Build-time app configuration. Runs before `start`, `build`, and `test`.
//
// 1. src/environments/app-config.ts
//    - Firebase web config from environment variables. These values are public
//      identifiers (they ship in the built JavaScript) but stay out of git so
//      every deployer uses their own projects. With no variables set, the app
//      targets the local emulators (project demo-arthapath).
//    - repoRef: the git branch that GitHub links point to. `main` for
//      production builds, `development` otherwise (UAT, PRs, local).
//    - appVersion: MAJOR.MINOR from package.json + BUILD = number of commits
//      on HEAD. Every merge (and so every deploy) increases it, and any commit
//      always builds the same version. Also written to version.json, which
//      running apps poll to offer a reload when a newer version is deployed.
//
// 2. src/generated/legal/*.html
//    - The privacy policy and terms rendered from docs/product/*.md, so the app
//      always shows the documents of the branch it was built from. Relative
//      links are rewritten to GitHub URLs on that same branch.
import { execSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, posix } from 'node:path';
import { Marked } from 'marked';

const REPO = 'https://github.com/deepakdaneva/arthapath';
const env = process.env;

// --- Firebase config -------------------------------------------------------
const real = Boolean(env.FIREBASE_PROJECT_ID && env.FIREBASE_API_KEY && env.FIREBASE_APP_ID);
const firebaseConfig = real
  ? {
      apiKey: env.FIREBASE_API_KEY,
      authDomain: env.FIREBASE_AUTH_DOMAIN || `${env.FIREBASE_PROJECT_ID}.firebaseapp.com`,
      projectId: env.FIREBASE_PROJECT_ID,
      appId: env.FIREBASE_APP_ID,
      messagingSenderId: env.FIREBASE_MESSAGING_SENDER_ID || '',
    }
  : {
      apiKey: 'demo-api-key',
      authDomain: 'demo-arthapath.firebaseapp.com',
      projectId: 'demo-arthapath',
      appId: 'demo-app-id',
      messagingSenderId: '',
    };

// --- Repository ref --------------------------------------------------------
// APP_REPO_REF overrides; on GitHub Actions pushes GITHUB_REF_NAME is the branch.
const ref = env.APP_REPO_REF || (env.GITHUB_REF_NAME === 'main' ? 'main' : 'development');
if (!/^[A-Za-z0-9._/-]+$/.test(ref)) throw new Error(`Invalid repo ref: ${ref}`);

// --- Version ---------------------------------------------------------------
const git = (cmd) => {
  try {
    return execSync(`git ${cmd}`, { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  } catch {
    return '';
  }
};
if (git('rev-parse --is-shallow-repository') === 'true') {
  throw new Error('Shallow git clone: fetch full history (fetch-depth: 0) so the build number is correct.');
}
const [major, minor] = JSON.parse(readFileSync('package.json', 'utf8')).version.split('.');
const build = Number(git('rev-list --count HEAD')) || 0;
const appVersion = `${major}.${minor}.${build}`;
const commit = git('rev-parse --short HEAD') || 'unknown';
const builtAt = new Date().toISOString();

mkdirSync('src/environments', { recursive: true });
writeFileSync(
  'src/environments/app-config.ts',
  `// Generated by scripts/write-app-config.mjs. Do not edit or commit.
export const firebaseConfig = ${JSON.stringify(firebaseConfig, null, 2)} as const;
export const useEmulators = ${!real};
export const repoUrl = ${JSON.stringify(REPO)};
export const repoRef = ${JSON.stringify(ref)};
export const appVersion = ${JSON.stringify(appVersion)};
export const appCommit = ${JSON.stringify(commit)};
export const appBuiltAt = ${JSON.stringify(builtAt)};
`,
);
mkdirSync('src/generated', { recursive: true });
writeFileSync('src/generated/version.json', `${JSON.stringify({ version: appVersion, commit, builtAt })}
`);

// --- Legal documents -------------------------------------------------------
/** Rewrites a link found in docs/product/<file>.md to an absolute URL. */
function rewriteHref(href, sourceFile, gitRef) {
  if (/^(https?:|mailto:|#)/i.test(href)) return href;
  const [path, hash = ''] = href.split('#');
  const resolved = posix.normalize(posix.join(posix.dirname(sourceFile), path));
  if (resolved.startsWith('..')) return '#';
  const kind = href.endsWith('/') ? 'tree' : 'blob';
  return `${REPO}/${kind}/${gitRef}/${resolved}${hash ? `#${hash}` : ''}`;
}

const DOCS = [
  ['docs/product/PRIVACY_POLICY.md', 'privacy.html'],
  ['docs/product/TERMS_OF_SERVICE.md', 'terms.html'],
];

for (const [source, target] of DOCS) {
  const marked = new Marked({
    gfm: true,
    walkTokens(token) {
      if (token.type === 'link') token.href = rewriteHref(token.href, source, ref);
    },
    renderer: {
      // Raw HTML in the markdown is not passed through.
      html: () => '',
      // External links open in a new tab without leaking the opener.
      link({ href, tokens }) {
        const text = this.parser.parseInline(tokens);
        const safe = href.replace(/"/g, '%22');
        return href.startsWith('#')
          ? `<a href="${safe}">${text}</a>`
          : `<a href="${safe}" target="_blank" rel="noopener noreferrer">${text}</a>`;
      },
    },
  });
  const html = await marked.parse(readFileSync(source, 'utf8'));
  const out = `src/generated/legal/${target}`;
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, html);
}

console.log(
  `App config: ${real ? firebaseConfig.projectId : 'local emulators (demo-arthapath)'}, repo ref ${ref}, version ${appVersion} (${commit})`,
);
